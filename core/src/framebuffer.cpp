Framebuffer::Framebuffer() : pixels_(BYTES, 0) {}

void Framebuffer::clear(uint32_t rgba) {
    uint32_t* p = reinterpret_cast<uint32_t*>(pixels_.data());
    const size_t n = PIXELS;
    for (size_t i = 0; i < n; ++i) p[i] = rgba;
}

void Framebuffer::setPixel(int x, int y, uint32_t rgba) {
    if (x < 0 || y < 0 || x >= WIDTH || y >= HEIGHT) return;
    setPixelIndex(static_cast<uint32_t>(y) * WIDTH + static_cast<uint32_t>(x), rgba);
}

void Framebuffer::setPixelIndex(uint32_t index, uint32_t rgba) {
    if (index >= PIXELS) return;
    const size_t o = static_cast<size_t>(index) * 4;
    pixels_[o + 0] = static_cast<uint8_t>(rgba & 0xFF);
    pixels_[o + 1] = static_cast<uint8_t>((rgba >> 8) & 0xFF);
    pixels_[o + 2] = static_cast<uint8_t>((rgba >> 16) & 0xFF);
    pixels_[o + 3] = static_cast<uint8_t>((rgba >> 24) & 0xFF);
}

void Framebuffer::fillRect(int x, int y, int w, int h, uint32_t rgba) {
    for (int j = 0; j < h; ++j)
        for (int i = 0; i < w; ++i)
            setPixel(x + i, y + j, rgba);
}

void Framebuffer::drawLine(int x0, int y0, int x1, int y1, uint32_t rgba) {
    int dx = std::abs(x1 - x0);
    int dy = -std::abs(y1 - y0);
    int sx = x0 < x1 ? 1 : -1;
    int sy = y0 < y1 ? 1 : -1;
    int err = dx + dy;

    for (;;) {
        setPixel(x0, y0, rgba);
        if (x0 == x1 && y0 == y1) break;
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void Framebuffer::drawChar(int x, int y, char c, uint32_t rgba) {
    int idx = static_cast<unsigned char>(c) - 32;
    if (idx < 0 || idx >= 96) idx = 0;
    const uint8_t* glyph = FONT8X8[idx];
    for (int row = 0; row < 8; ++row) {
        uint8_t bits = glyph[row];
        for (int col = 0; col < 8; ++col) {
            if (bits & (1u << col)) setPixel(x + col, y + row, rgba);
        }
    }
}

void Framebuffer::drawText(int x, int y, const std::string& text, uint32_t rgba) {
    int cx = x;
    int cy = y;
    for (char c : text) {
        if (c == '\n') { cx = x; cy += 10; continue; }
        drawChar(cx, cy, c, rgba);
        cx += 8;
        if (cx + 8 > WIDTH) { cx = x; cy += 10; }
    }
}